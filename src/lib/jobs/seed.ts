function daysAgoIso(days: number): string {
  const d = new Date();
  d.setUTCDate(d.getUTCDate() - days);
  d.setUTCHours(9, 0, 0, 0);
  return d.toISOString();
}

function job(
  partial: SeedInput,
): Job {
  return {
    ...partial,
    postedAt: daysAgoIso(partial.daysAgo),
    refreshedAt: new Date().toISOString(),
    isNew: partial.daysAgo <= 2,
  };
}

